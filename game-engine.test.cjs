const assert = require('node:assert/strict');
require('./game-engine.js');
const game = globalThis.CP11_GAME;
const rules={low:1,high:20,mode:'limited',limit:5,invalidCounts:false,prompt:'Guess?',lowMessage:'low',highMessage:'high',invalidMessage:'outside',winMessage:'win',loseMessage:'loss'};
let s=game.start(rules,17);
assert.equal(game.guess(s,'10').type,'low');
assert.equal(game.guess(s,'19').type,'high');
assert.equal(game.guess(s,'17').outcome,'win');
assert.equal(s.used,3);
assert.equal(s.secret,17);
assert.equal(game.guess(s,'1').type,'ended');
assert.equal(s.used,3);
s=game.start(rules,17);
for (const raw of ['', 'hello', '1.5', '1e1']) assert.equal(game.guess(s,raw).type,'text');
assert.equal(s.used,0);
assert.equal(game.guess(s,'0').type,'range');
assert.equal(game.guess(s,'21').type,'range');
assert.equal(s.used,0);
for(let i=0;i<4;i++)game.guess(s,'1');
assert.equal(game.guess(s,'17').outcome,'win');
assert.equal(s.used,5);
s=game.start(rules,17);
for(let i=0;i<5;i++)game.guess(s,'1');
assert.equal(s.outcome,'loss');
assert.match(s.history.at(-1).message,/17/);
assert.equal(game.guess(s,'17').type,'ended');
s=game.start({...rules,invalidCounts:true,limit:1},17);
assert.equal(game.guess(s,'21').outcome,'loss');
assert.equal(s.used,1);
s=game.start({...rules,mode:'until'},17);
for(let i=0;i<12;i++)game.guess(s,'1');
assert.equal(s.ended,false);
assert.equal(game.guess(s,'17').outcome,'win');
assert.equal(s.used,13);
for(const secret of [1,20]) {s=game.start(rules,secret);assert.equal(game.guess(s,String(secret)).outcome,'win');}
s=game.start({...rules,low:-10,high:0},-5);
assert.equal(game.guess(s,'-8').type,'low');
assert.equal(game.guess(s,' -5 ').outcome,'win');
assert.throws(()=>game.start({...rules,low:20,high:1}));
assert.throws(()=>game.start({...rules,low:NaN}));
assert.throws(()=>game.start({...rules,limit:0}));
assert.throws(()=>game.start({...rules,invalidMessage:''}));
assert.throws(()=>game.start(rules,21));
console.log('Game preview checks passed: feedback, limits, inclusive endpoints, invalid inputs, fixed secrets, stopping, and last-chance wins.');
